DECLARE
NUM1 NUMBER:=7;
NUM2 NUMBER:=6;
N NUMBER:=2;
R NUMBER;

BEGIN
    R:=MOD(NUM1, 2);
    IF R=0 THEN
    DBMS_OUTPUT.PUT_LINE(NUM1 || ' IS EVEN');
    ELSE
    DBMS_OUTPUT.PUT_LINE(NUM1 || ' IS ODD');
    END IF;

    R:=MOD(NUM2, 2);
    IF R=0 THEN
    DBMS_OUTPUT.PUT_LINE(NUM2 || ' IS EVEN');
    ELSE
    DBMS_OUTPUT.PUT_LINE(NUM2 || ' IS ODD');
    END IF;
END;
